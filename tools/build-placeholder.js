// Generates placeholder data/quests/<id>.js and data/quests/<id>.source.json.
// Usage: node tools/build-placeholder.js
const fs = require('fs');
const path = require('path');
const Q = require('../js/shared/codec.js');

function st(i, names, lat, lng) {
  return {
    prompt: { uk: `ЗАГЛУШКА: текст завдання №${i}. Відгадайте місце.`, en: `PLACEHOLDER: puzzle text #${i}. Guess the place.` },
    hints: [
      { uk: `Заглушка: підказка 1 до завдання ${i}`, en: `Placeholder: hint 1 for task ${i}` },
      { uk: `Заглушка: підказка 2 до завдання ${i}`, en: `Placeholder: hint 2 for task ${i}` },
      { uk: `Заглушка: підказка 3 до завдання ${i}`, en: `Placeholder: hint 3 for task ${i}` }
    ],
    names, lat, lng, radius: 100,
    clue: { uk: `Заглушка: підказка до кросворду ${i}`, en: `Placeholder: crossword clue ${i}` }
  };
}

const source = {
  id: 'placeholder-quest',
  title: { uk: 'Квест містом (демо)', en: 'City quest (demo)' },
  settings: Q.data.mergeSettings(),
  stations: [
    st(1, ['Майдан Незалежності', 'Maidan Nezalezhnosti'], 50.4501, 30.5234),
    st(2, ['Золоті ворота', 'Golden Gate'], 50.4486, 30.5139),
    st(3, ['Києво-Печерська лавра', 'Kyiv Pechersk Lavra'], 50.4346, 30.5572)
  ]
};

if (!Q.data.isValidQuestId(source.id)) throw new Error('invalid quest id: ' + source.id);
const questDir = path.join(__dirname, '..', 'data', 'quests');
fs.mkdirSync(questDir, { recursive: true });
fs.writeFileSync(path.join(questDir, source.id + '.source.json'), JSON.stringify(source, null, 2) + '\n');
fs.writeFileSync(path.join(questDir, source.id + '.js'),
  '/* Generated by editor.html. Save as data/quests/' + source.id + '.js */\nwindow.QUEST_DATA = ' +
  JSON.stringify(Q.data.pack(source), null, 1) + ';\n');
console.log('written');
